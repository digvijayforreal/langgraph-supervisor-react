
from pathlib import Path
from xml.sax.saxutils import escape

from langchain_core.tools import tool
from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Preformatted,
)
from reportlab.lib.colors import HexColor


PROJECT_ROOT = Path(__file__).resolve().parents[1]
REPORT_DIR = PROJECT_ROOT / "data" / "react_reports"


@tool
def react_generate_pdf(title: str, content: str) -> str:
    """Generate a downloadable PDF report from supplied research or analysis.
    Include source URLs in content when available. Returns the generated
    PDF's absolute path and a relative path for application integration."""

    if not title.strip() or not content.strip():
        return "Error: title and content must not be empty."

    try:
        REPORT_DIR.mkdir(parents=True, exist_ok=True)

        safe_title = "".join(
            char if char.isalnum() or char in "-_ " else "_"
            for char in title
        ).strip()

        if not safe_title:
            safe_title = "react_report"

        # Keep generated filenames predictable and safe.
        import uuid
        filename = f"{safe_title[:60]}_{uuid.uuid4().hex[:8]}.pdf"
        output_path = REPORT_DIR / filename

        styles = getSampleStyleSheet()
        styles.add(ParagraphStyle(
            name="ReportTitle",
            parent=styles["Title"],
            fontSize=20,
            leading=25,
            alignment=TA_CENTER,
            textColor=HexColor("#243447"),
            spaceAfter=18,
        ))
        styles.add(ParagraphStyle(
            name="ReportBody",
            parent=styles["BodyText"],
            fontSize=10,
            leading=15,
            spaceAfter=8,
        ))

        story = [
            Paragraph(escape(title), styles["ReportTitle"]),
            Paragraph(
                "Generated by the Gemini ReAct workflow",
                styles["Italic"],
            ),
            Spacer(1, 8 * mm),
        ]

        # Preserve paragraphs and line breaks while escaping markup.
        for block in content.split("\n\n"):
            safe_block = escape(block.strip()).replace("\n", "<br/>")
            if safe_block:
                story.append(
                    Paragraph(safe_block, styles["ReportBody"])
                )
                story.append(Spacer(1, 3 * mm))

        document = SimpleDocTemplate(
            str(output_path),
            pagesize=A4,
            rightMargin=20 * mm,
            leftMargin=20 * mm,
            topMargin=20 * mm,
            bottomMargin=20 * mm,
            title=title[:200],
        )

        document.build(story)

        return (
            "PDF generated successfully.\n"
            f"Filename: {filename}\n"
            f"Absolute path: {output_path.resolve()}\n"
            f"Relative path: data/react_reports/{filename}"
        )

    except Exception as error:
        return f"PDF generation failed: {error}"
